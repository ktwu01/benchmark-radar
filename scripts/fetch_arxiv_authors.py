"""Read benchmark authors from arXiv into data/catalog/benchmark_authors.yml (#933).

Only records whose own introducing paper is on arXiv are filled (see
``benchmark_radar.catalog_authors.introducing_arxiv_id``). Run
``benchmark-radar normalize-catalog`` first: this reads the normalized source
records it writes under data/catalog/. Existing entries are kept, so a rerun
fetches only papers not yet recorded; pass --refresh to re-read them all.

The arXiv API asks for at most one request every three seconds. Each request
carries up to 100 ids, failed requests back off exponentially (1 to 60
seconds, up to five retries), and every finished batch is checkpointed so an
interrupted run resumes where it stopped. The checkpoint is deleted once the
file is written, and --refresh ignores it.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
import xml.etree.ElementTree as ET
from datetime import UTC, datetime
from pathlib import Path

import yaml

from benchmark_radar.catalog_authors import DEFAULT_AUTHORS_PATH, introducing_arxiv_id

API = "https://export.arxiv.org/api/query"
ATOM = {"a": "http://www.w3.org/2005/Atom"}
RECORD_FILES = ("claire_radar_source_records.jsonl", "model_reports_source_records.jsonl")
USER_AGENT = "benchmark-radar/authors (+https://github.com/ktwu01/benchmark-radar)"
HEADER = """\
# Benchmark authors read from the arXiv metadata of each benchmark's own
# introducing paper (#933). Generated by scripts/fetch_arxiv_authors.py; rerun it
# rather than editing names by hand. Exact source keys preserve the catalog's
# one-record-per-source population. A record whose paper only evaluates or
# aggregates benchmarks is absent: that paper's authors did not make it.
"""


def eligible(records_dir: Path) -> dict[str, str]:
    """Map each eligible source key to its introducing arXiv id."""
    found = {}
    for name in RECORD_FILES:
        for line in (records_dir / name).read_text(encoding="utf-8").splitlines():
            record = json.loads(line)
            paper = introducing_arxiv_id(record)
            if paper:
                found[record["key"]] = paper
    return dict(sorted(found.items()))


def request(ids: list[str], *, retries: int = 5) -> bytes:
    query = urllib.parse.urlencode({"id_list": ",".join(ids), "max_results": len(ids)})
    req = urllib.request.Request(f"{API}?{query}", headers={"User-Agent": USER_AGENT})
    delay = 1.0
    for attempt in range(retries + 1):
        try:
            with urllib.request.urlopen(req, timeout=60) as response:
                return response.read()
        except (urllib.error.URLError, TimeoutError) as exc:
            if attempt == retries:
                raise
            print(f"retry in {delay:.0f}s after {exc}", file=sys.stderr)
            time.sleep(delay)
            delay = min(delay * 2, 60.0)
    raise AssertionError("unreachable")


def parse(payload: bytes) -> dict[str, list[str]]:
    """Map each returned arXiv id (without version) to its author names."""
    authors = {}
    for entry in ET.fromstring(payload).findall("a:entry", ATOM):
        link = (entry.findtext("a:id", default="", namespaces=ATOM) or "").strip()
        paper = link.rsplit("/abs/", 1)[-1].split("v")[0]
        names = [
            " ".join((author.findtext("a:name", default="", namespaces=ATOM) or "").split())
            for author in entry.findall("a:author", ATOM)
        ]
        names = [name for name in names if name]
        if paper and names:
            authors[paper] = names
    return authors


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--records-dir", type=Path, default=Path("data/catalog"))
    parser.add_argument("--output", type=Path, default=DEFAULT_AUTHORS_PATH)
    parser.add_argument("--checkpoint", type=Path, default=Path("/tmp/arxiv-authors.json"))
    parser.add_argument("--batch", type=int, default=100)
    parser.add_argument("--delay", type=float, default=3.0)
    parser.add_argument("--refresh", action="store_true")
    args = parser.parse_args()

    wanted = eligible(args.records_dir)
    existing = {}
    if args.output.exists() and not args.refresh:
        existing = (yaml.safe_load(args.output.read_text(encoding="utf-8")) or {}).get(
            "benchmarks"
        ) or {}
    # The checkpoint only resumes an interrupted run: a refresh re-reads every
    # paper, and a finished run deletes it below.
    fetched: dict[str, list[str]] = {}
    if args.checkpoint.exists() and not args.refresh:
        fetched = json.loads(args.checkpoint.read_text(encoding="utf-8"))
    missing = sorted(
        {paper for key, paper in wanted.items() if key not in existing} - fetched.keys()
    )
    print(f"{len(wanted)} eligible records, {len(missing)} papers to fetch")
    for start in range(0, len(missing), args.batch):
        batch = missing[start : start + args.batch]
        fetched.update(parse(request(batch)))
        args.checkpoint.write_text(json.dumps(fetched, ensure_ascii=False), encoding="utf-8")
        print(f"fetched {min(start + args.batch, len(missing))}/{len(missing)}")
        time.sleep(args.delay)

    today = datetime.now(UTC).date().isoformat()
    benchmarks = {}
    absent = []
    for key, paper in wanted.items():
        if key in existing:
            benchmarks[key] = existing[key]
        elif paper in fetched:
            benchmarks[key] = {
                "source_url": f"https://arxiv.org/abs/{paper}",
                "retrieved_at": today,
                "authors": fetched[paper],
            }
        else:
            absent.append(key)
    body = yaml.safe_dump(
        {"schema_version": 1, "benchmarks": benchmarks},
        allow_unicode=True,
        sort_keys=False,
        width=100,
    )
    args.output.write_text(HEADER + body, encoding="utf-8")
    args.checkpoint.unlink(missing_ok=True)
    print(f"wrote {len(benchmarks)} records to {args.output}; {len(absent)} not on arXiv API")
    for key in absent:
        print(f"  no arXiv metadata: {key} ({wanted[key]})")


if __name__ == "__main__":
    main()
