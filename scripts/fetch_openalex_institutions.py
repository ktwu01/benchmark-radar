"""Read benchmark institutions from OpenAlex into data/catalog/benchmark_institutions.yml (#933).

Only records whose own introducing paper is on arXiv are filled (see
``benchmark_radar.catalog_authors.introducing_arxiv_id``). Each paper is looked
up by the DOI arXiv registers for it, and the institutions are OpenAlex's
linked institutions in first-appearance order across the authorships. A paper
OpenAlex does not hold, or holds with no linked institution, stays absent.

Run ``benchmark-radar normalize-catalog`` first: this reads the normalized
source records it writes under data/catalog/. Existing entries are kept, so a
rerun fetches only papers not yet recorded; pass --refresh to re-read them all.

Without an API key, OpenAlex gives every caller on a network one small shared
daily budget, so each request carries 50 DOIs. Set OPENALEX_API_KEY to use a
key. Failed requests back off exponentially (1 to 60 seconds, up to five
retries), and every finished batch is checkpointed so an interrupted run
resumes where it stopped. The checkpoint is deleted once the file is written,
and --refresh ignores it.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import yaml

from benchmark_radar.catalog_authors import introducing_arxiv_id
from benchmark_radar.catalog_institutions import DEFAULT_INSTITUTIONS_PATH, arxiv_doi

API = "https://api.openalex.org/works"
RECORD_FILES = ("claire_radar_source_records.jsonl", "model_reports_source_records.jsonl")
USER_AGENT = "benchmark-radar/institutions (+https://github.com/ktwu01/benchmark-radar)"
HEADER = """\
# Institutions OpenAlex links to the authorships of each benchmark's own
# introducing arXiv paper, in first-appearance order (#933). Generated by
# scripts/fetch_openalex_institutions.py; rerun it rather than editing names by
# hand. These are OpenAlex's linked institution names, not raw affiliation
# strings. A record whose paper only evaluates or aggregates benchmarks is
# absent: that paper's institutions did not make it.
"""


def eligible(records_dir: Path) -> dict[str, str]:
    """Map each eligible source key to its introducing arXiv id."""
    found = {}
    for name in RECORD_FILES:
        for line in (records_dir / name).read_text(encoding="utf-8").splitlines():
            record = json.loads(line)
            paper = introducing_arxiv_id(record)
            if paper:
                found[record["key"]] = paper
    return dict(sorted(found.items()))


def request(papers: list[str], *, retries: int = 5) -> dict[str, Any]:
    params = {
        "filter": "doi:" + "|".join(arxiv_doi(paper) for paper in papers),
        "select": "id,doi,authorships",
        "per-page": "200",
    }
    key = os.environ.get("OPENALEX_API_KEY")
    if key:
        params["api_key"] = key
    req = urllib.request.Request(
        f"{API}?{urllib.parse.urlencode(params)}", headers={"User-Agent": USER_AGENT}
    )
    delay = 1.0
    for attempt in range(retries + 1):
        try:
            with urllib.request.urlopen(req, timeout=60) as response:
                return json.loads(response.read())
        except (urllib.error.URLError, TimeoutError) as exc:
            # A 4xx other than 429 is a bad request; retrying spends the shared
            # daily budget for nothing.
            code = getattr(exc, "code", None)
            if attempt == retries or (code is not None and code != 429 and code < 500):
                raise
            print(f"retry in {delay:.0f}s after {exc}", file=sys.stderr)
            time.sleep(delay)
            delay = min(delay * 2, 60.0)
    raise AssertionError("unreachable")


def institutions(work: dict[str, Any]) -> list[str]:
    """Linked institution names in first-appearance order, each once."""
    seen_ids: set[str] = set()
    names: list[str] = []
    for authorship in work.get("authorships") or []:
        for institution in authorship.get("institutions") or []:
            identifier = str(institution.get("id") or "")
            name = " ".join(str(institution.get("display_name") or "").split())
            if not identifier or not name or identifier in seen_ids:
                continue
            seen_ids.add(identifier)
            if name not in names:
                names.append(name)
    return names


def parse(payload: dict[str, Any], papers: list[str]) -> dict[str, dict[str, Any] | None]:
    """Map each requested paper to its OpenAlex work, or None when uncertain.

    A DOI that matches no work, or more than one, records nothing.
    """
    by_doi: dict[str, list[dict[str, Any]]] = {}
    for work in payload.get("results") or []:
        doi = str(work.get("doi") or "").lower().removeprefix("https://doi.org/")
        by_doi.setdefault(doi, []).append(work)
    found: dict[str, dict[str, Any] | None] = {}
    for paper in papers:
        works = by_doi.get(arxiv_doi(paper).lower(), [])
        names = institutions(works[0]) if len(works) == 1 else []
        found[paper] = {"work": works[0]["id"], "institutions": names} if names else None
    return found


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--records-dir", type=Path, default=Path("data/catalog"))
    parser.add_argument("--output", type=Path, default=DEFAULT_INSTITUTIONS_PATH)
    parser.add_argument("--checkpoint", type=Path, default=Path("/tmp/openalex-institutions.json"))
    parser.add_argument("--batch", type=int, default=50)
    parser.add_argument("--delay", type=float, default=1.0)
    parser.add_argument("--refresh", action="store_true")
    args = parser.parse_args()

    wanted = eligible(args.records_dir)
    existing = {}
    if args.output.exists() and not args.refresh:
        existing = (yaml.safe_load(args.output.read_text(encoding="utf-8")) or {}).get(
            "benchmarks"
        ) or {}
    # The checkpoint only resumes an interrupted run: a refresh re-reads every
    # paper, and a finished run deletes it below.
    fetched: dict[str, dict[str, Any] | None] = {}
    if args.checkpoint.exists() and not args.refresh:
        fetched = json.loads(args.checkpoint.read_text(encoding="utf-8"))
    missing = sorted(
        {paper for key, paper in wanted.items() if key not in existing} - fetched.keys()
    )
    print(f"{len(wanted)} eligible records, {len(missing)} papers to fetch")
    for start in range(0, len(missing), args.batch):
        batch = missing[start : start + args.batch]
        fetched.update(parse(request(batch), batch))
        args.checkpoint.write_text(json.dumps(fetched, ensure_ascii=False), encoding="utf-8")
        print(f"fetched {min(start + args.batch, len(missing))}/{len(missing)}")
        time.sleep(args.delay)

    today = datetime.now(UTC).date().isoformat()
    benchmarks = {}
    absent = []
    for key, paper in wanted.items():
        if key in existing:
            benchmarks[key] = existing[key]
        elif fetched.get(paper):
            benchmarks[key] = {
                "source_url": fetched[paper]["work"],
                "doi": arxiv_doi(paper),
                "retrieved_at": today,
                "institutions": fetched[paper]["institutions"],
            }
        else:
            absent.append(key)
    body = yaml.safe_dump(
        {"schema_version": 1, "benchmarks": benchmarks},
        allow_unicode=True,
        sort_keys=False,
        width=100,
    )
    args.output.write_text(HEADER + body, encoding="utf-8")
    args.checkpoint.unlink(missing_ok=True)
    print(f"wrote {len(benchmarks)} records to {args.output}; {len(absent)} without institutions")
    for key in absent:
        print(f"  no OpenAlex institutions: {key} ({wanted[key]})")


if __name__ == "__main__":
    main()
