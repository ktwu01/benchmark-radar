"""Facts the Latest releases ranking reads beyond attention (#1120).

Two committed files, refreshed by ``scripts/fetch_release_signals.py`` from the
daily workflow and read by ``release_leaderboard`` at build time, so a build
never touches the network:

* ``data/release_institutions.yml``: for each arXiv paper in the release
  cohort, the institutions behind it with their basis (OpenAlex or the
  paper's own arXiv HTML) and source URL.
* ``data/release_repos.yml``: for each GitHub repository whose stars a release
  is ranked on, its size, stars on the check date, archived flag, creation and
  last-push dates, and whether its root holds anything beyond a README,
  licence, citation file or image folder.

A release is held back (listed, unranked, with the reason) when its
repository is a placeholder, is archived, or is confirmed gone (404 on the
repository endpoint, which follows renames). Stars and size never hold a
release back: stars are already part of the score, and a small repository
often means the data lives on Hugging Face (backtest in #1130).

Missing is unknown: a paper or repository absent from these files, or a field
left null, gets no affiliation credit and no hold-back.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from datetime import date
from pathlib import Path
from typing import Any
from urllib.parse import urlsplit

import yaml

DEFAULT_RELEASE_INSTITUTIONS_PATH = Path("data/release_institutions.yml")
DEFAULT_RELEASE_REPOS_PATH = Path("data/release_repos.yml")
SCHEMA_VERSION = 1

# A repository larger than this cannot be README-only in practice, so its root
# is not listed (saves one API call per large repository). A README with very
# large images above this size is missed, which only leaves it ranked.
LISTING_MAX_KB = 2048

HELD_BACK_PLACEHOLDER = "placeholder_repository"
HELD_BACK_ARCHIVED = "repository_archived"
HELD_BACK_UNAVAILABLE = "repository_unavailable"

# Root entries that do not make a benchmark: what a "code coming soon"
# repository holds. Compared case-insensitively, by name or name stem.
_PLACEHOLDER_FILE_STEMS = frozenset(
    {"readme", "license", "licence", "copying", "citation", "notice", "code_of_conduct"}
)
_PLACEHOLDER_NAMES = frozenset(
    {
        ".gitignore",
        ".gitattributes",
        ".github",
        ".ds_store",
        "assets",
        "asset",
        "images",
        "image",
        "imgs",
        "img",
        "figures",
        "figure",
        "figs",
        "fig",
        "static",
        "media",
        "pics",
    }
)
# Hosts a README links to when the benchmark's data ships outside the repository
# (ShaohuaDong2021/RGBD20K: dataset and models on Google Drive, code "will be
# released"). For a benchmark the data is the deliverable, so such a README is
# not a placeholder. A link to someone else's dataset passes too; that only
# leaves a non-benchmark ranked, the error principle.md tolerates.
DATA_HOSTS = re.compile(
    r"huggingface\.co/datasets|hf\.co/datasets|drive\.google\.com|zenodo\.org"
    r"|kaggle\.com/datasets|figshare\.com|dropbox\.com|1drv\.ms|onedrive\.live\.com"
    r"|sharepoint\.com|pan\.baidu\.com|modelscope\.cn/datasets|osf\.io|dataverse"
    r"|s3(?:[.-][a-z0-9-]+)?\.amazonaws\.com|storage\.googleapis\.com|physionet\.org"
    r"|openxlab\.org\.cn/datasets",
    re.IGNORECASE,
)
_IMAGE_SUFFIXES = (".png", ".jpg", ".jpeg", ".gif", ".svg", ".webp", ".pdf")

_HEADER_INSTITUTIONS = """\
# Institutions behind each arXiv paper in the Latest releases cohort (#1120).
# Generated by scripts/fetch_release_signals.py; rerun it rather than editing
# by hand. basis openalex_linked_institutions holds OpenAlex's normalized
# names; arxiv_html_affiliations holds the paper's own affiliations as printed,
# cleaned, used while OpenAlex has not indexed the paper. Only the OpenAlex
# basis is counted in the institution ranking.
"""

_HEADER_REPOS = """\
# The GitHub repositories the Latest releases cohort is ranked on (#1120).
# Generated by scripts/fetch_release_signals.py; rerun it, never hand-edit.
# size_kb, stars_at_check, archived, created_at and pushed_at come from the
# GitHub API on retrieved_at. placeholder: the root holds only a README,
# licence, citation file or image folders. unavailable: the repository
# endpoint answers 404 (it follows renames). A release on a placeholder,
# archived or unavailable repository is listed but not ranked. null means
# not yet checked, which never holds a release back.
"""


def is_placeholder_root(names: list[str]) -> bool:
    """Whether a repository root holds nothing that could be a benchmark."""
    for raw in names:
        name = str(raw).strip().lower()
        if not name:
            continue
        if name in _PLACEHOLDER_NAMES or name.endswith(_IMAGE_SUFFIXES):
            continue
        if name.split(".", 1)[0] in _PLACEHOLDER_FILE_STEMS:
            continue
        return False
    return True


def readme_data_link(text: str | None) -> str | None:
    """The first dataset host a README links to, or None."""
    match = DATA_HOSTS.search(str(text or ""))
    return match.group(0).lower() if match else None


def readme_name(names: list[str]) -> str | None:
    """The README file among a repository's root entries, if any."""
    return next((n for n in names if str(n).lower().split(".", 1)[0] == "readme"), None)


def github_repo(url: str | None) -> str | None:
    """``owner/name`` for a github.com repository URL, lower-cased, else None."""
    parts = urlsplit(str(url or ""))
    if parts.netloc.lower() not in {"github.com", "www.github.com"}:
        return None
    segments = [segment for segment in parts.path.split("/") if segment]
    if len(segments) < 2:
        return None
    return f"{segments[0]}/{segments[1].removesuffix('.git')}".lower()


@dataclass(frozen=True)
class ReleaseSignals:
    """What the ranking reads: institutions by arXiv id, placeholders by repo."""

    institutions: dict[str, dict[str, Any]] = field(default_factory=dict)
    repos: dict[str, dict[str, Any]] = field(default_factory=dict)

    def paper(self, paper: str | None) -> dict[str, Any] | None:
        return self.institutions.get(paper) if paper else None

    def is_placeholder(self, url: str | None) -> bool:
        return self.held_back(url) == HELD_BACK_PLACEHOLDER

    def held_back(self, url: str | None) -> str | None:
        """Why a release ranked on this repository is held back, or None."""
        repo = github_repo(url)
        row = (self.repos.get(repo) or {}) if repo else {}
        if row.get("unavailable") is True:
            return HELD_BACK_UNAVAILABLE
        if row.get("archived") is True:
            return HELD_BACK_ARCHIVED
        if row.get("placeholder") is True:
            return HELD_BACK_PLACEHOLDER
        return None


def _read(path: Path, key: str) -> dict[str, dict[str, Any]]:
    try:
        payload = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    except FileNotFoundError:
        return {}
    if not isinstance(payload, dict) or payload.get("schema_version") != SCHEMA_VERSION:
        raise ValueError(f"{path}: expected schema_version {SCHEMA_VERSION}")
    rows = payload.get(key) or {}
    if not isinstance(rows, dict):
        raise ValueError(f"{path}: {key} must be a mapping")
    return {str(name): dict(row) for name, row in rows.items() if isinstance(row, dict)}


def load_release_signals(
    institutions_path: Path = DEFAULT_RELEASE_INSTITUTIONS_PATH,
    repos_path: Path = DEFAULT_RELEASE_REPOS_PATH,
) -> ReleaseSignals:
    """Load both files. A missing file is no signal; a malformed one fails loudly."""
    institutions = _read(institutions_path, "papers")
    for paper, row in institutions.items():
        names = row.get("institutions")
        if not re.fullmatch(r"\d{4}\.\d{4,5}", paper) or not isinstance(names, list):
            raise ValueError(f"{institutions_path}: {paper}: malformed entry")
    return ReleaseSignals(institutions=institutions, repos=_read(repos_path, "repos"))


def _dump(path: Path, header: str, key: str, rows: dict[str, Any]) -> None:
    body = yaml.safe_dump(
        {"schema_version": SCHEMA_VERSION, key: dict(sorted(rows.items()))},
        allow_unicode=True,
        sort_keys=False,
        width=100,
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(header + body, encoding="utf-8")


def write_release_institutions(path: Path, rows: dict[str, dict[str, Any]]) -> None:
    _dump(path, _HEADER_INSTITUTIONS, "papers", rows)


def write_release_repos(path: Path, rows: dict[str, dict[str, Any]]) -> None:
    _dump(path, _HEADER_REPOS, "repos", rows)


def needs_institution_refresh(row: dict[str, Any] | None, today: date, *, days: int = 3) -> bool:
    """A paper is looked up again until OpenAlex names its institutions.

    OpenAlex lags new papers, so a miss or an arXiv-HTML reading is retried
    every ``days`` days; an OpenAlex reading is final.
    """
    if not row:
        return True
    if row.get("basis") == "openalex_linked_institutions":
        return False
    try:
        checked = date.fromisoformat(str(row.get("retrieved_at")))
    except ValueError:
        return True
    return (today - checked).days >= days


def needs_repo_refresh(row: dict[str, Any] | None, today: date, *, days: int = 7) -> bool:
    """A placeholder is checked daily, since it can ship code any day; others weekly.

    A row whose placeholder status or availability is still unknown (null) is
    checked on the next run.
    """
    if not row:
        return True
    if row.get("unavailable") is None or (
        row.get("placeholder") is None and not row.get("archived") and not row.get("unavailable")
    ):
        return True
    try:
        checked = date.fromisoformat(str(row.get("retrieved_at")))
    except ValueError:
        return True
    return (today - checked).days >= (1 if row.get("placeholder") else days)
